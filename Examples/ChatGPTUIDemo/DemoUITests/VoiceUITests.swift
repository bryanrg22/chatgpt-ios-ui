import XCTest

final class VoiceUITests: XCTestCase {
    @MainActor func testVoiceChooserSessionSettingsAndEnd() {
        let app = XCUIApplication()
        app.launchArguments = ["--ui-test"]
        app.launch()
        app.buttons["composerPrimaryButton"].tap()
        XCTAssertTrue(app.buttons["voice.start"].waitForExistence(timeout: 3))
        capture("voice-chooser")
        app.buttons["Close voice chooser"].tap()
        XCTAssertTrue(app.buttons["composerPrimaryButton"].waitForExistence(timeout: 3))
        app.buttons["composerPrimaryButton"].tap()
        app.buttons["voice.start"].tap()
        XCTAssertTrue(app.buttons["voice.settings"].waitForExistence(timeout: 3))
        capture("voice-idle")
        app.buttons["Voice sidebar"].tap()
        XCTAssertTrue(app.buttons["voice.end"].exists)
        app.buttons["Voice attachments"].tap()
        XCTAssertTrue(app.buttons["Camera"].waitForExistence(timeout: 3))
        app.coordinate(withNormalizedOffset: CGVector(dx: 0.8, dy: 0.3)).tap()
        app.buttons["voice.mute"].tap()
        XCTAssertEqual(app.buttons["voice.mute"].label, "Mute voice")
        app.buttons["voice.mute"].tap()
        app.buttons["voice.settings"].tap()
        capture("voice-settings")
        app.buttons["Voice language"].tap()
        capture("voice-language")
        app.buttons["Afrikaans"].tap()
        app.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.2)).tap()
        app.buttons["voice.end"].tap()
        XCTAssertTrue(app.buttons["composerPrimaryButton"].waitForExistence(timeout: 3))
        app.buttons["composerPrimaryButton"].tap()
        XCTAssertTrue(app.buttons["voice.settings"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.buttons["voice.start"].exists)
        app.buttons["voice.end"].tap()
    }
    @MainActor func testVoiceTranscriptSharingAndLiveCamera() {
        let app = XCUIApplication()
        app.launchArguments = ["--ui-test"]
        app.launch()
        app.buttons["composerPrimaryButton"].tap()
        app.buttons["voice.start"].tap()
        app.buttons["Voice thinking"].tap()
        capture("voice-effort")
        app.buttons["Voice effort position 2"].tap()
        app.buttons["Voice effort position 2"].press(
            forDuration: 0.1, thenDragTo: app.buttons["Voice effort position 3"])
        capture("voice-effort-after-drag")
        XCTAssertTrue(app.staticTexts["High"].exists)
        app.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.25)).tap()
        let field = app.textFields["voice.composer"]
        field.tapToFocus()
        field.typeText("Help me plan a garden.\n")
        XCTAssertTrue(app.staticTexts["Help me plan a garden."].waitForExistence(timeout: 3))
        capture("voice-transcript")
        field.tap()
        capture("voice-transcript-keyboard")
        app.buttons["Voice attachments"].tap()
        capture("voice-attachments")
        app.buttons["More"].tap()
        capture("voice-more")
        app.buttons["Share screen"].tap()
        XCTAssertTrue(app.buttons["voice.shareContinue"].waitForExistence(timeout: 3))
        capture("voice-model-switch")
        app.buttons["Cancel voice model switch"].tap()
        XCTAssertFalse(app.buttons["voice.sharing"].exists)
        app.buttons["Voice attachments"].tap()
        app.buttons["More"].tap()
        app.buttons["Share screen"].tap()
        app.buttons["voice.shareContinue"].tap()
        XCTAssertTrue(app.buttons["voice.sharing"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.buttons["voice.settings"].exists)
        capture("voice-sharing")
        app.buttons["Voice attachments"].tap()
        capture("voice-stop-sharing-menu")
        app.buttons.matching(
            NSPredicate(format: "label == %@ AND identifier != %@", "Stop sharing screen", "voice.sharing")
        ).firstMatch.tap()
        XCTAssertFalse(app.buttons["voice.sharing"].exists)
        app.buttons["Voice attachments"].tap()
        app.buttons["Live video"].tap()
        XCTAssertTrue(app.buttons["Close live camera"].waitForExistence(timeout: 3))
        capture("voice-live-camera")
        app.buttons["Flip live camera"].tap()
        app.buttons["Live camera flash"].tap()
        app.buttons["Close live camera"].tap()
        XCTAssertTrue(app.staticTexts["Help me plan a garden."].exists)
        app.buttons["voice.end"].tap()
        XCTAssertTrue(app.buttons["composerPrimaryButton"].waitForExistence(timeout: 3))
    }
}
