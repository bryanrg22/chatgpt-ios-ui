import XCTest

final class FeatureWorkspaceUITests: XCTestCase {
    @MainActor func testEmptyFeatureDataHasNoSampleFallback() {
        let app = XCUIApplication()
        app.launchArguments = ["--ui-test", "--empty-finance"]
        app.launch()
        XCTAssertTrue(app.buttons["Finance menu"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.staticTexts["Housing"].exists)
        XCTAssertFalse(app.staticTexts["October"].exists)
        app.buttons["Accounts"].tap()
        XCTAssertFalse(app.staticTexts["EVERYDAY SAVINGS"].exists)
        app.buttons["Chats"].tap()
        XCTAssertFalse(app.staticTexts["Review sample balances"].exists)
        app.buttons["Transactions"].tap()
        XCTAssertFalse(app.staticTexts["Example employer"].exists)
        app.terminate()
        app.launchArguments = ["--ui-test", "--empty-health"]
        app.launch()
        XCTAssertTrue(app.buttons["Health menu"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.staticTexts["Step count"].exists)
        app.buttons["Accounts"].tap()
        XCTAssertFalse(app.staticTexts["Connected"].exists)
        app.buttons["health.add-account"].tap()
        XCTAssertTrue(app.textFields["health.provider-search"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.staticTexts["Apple Health"].exists)
        XCTAssertFalse(app.staticTexts["Function Health"].exists)
    }
    @MainActor func testHealthFeatureSetupAndDestinations() {
        let app = XCUIApplication()
        app.launchArguments = ["--ui-test"]
        app.launch()
        app.buttons["sidebarButton"].tap()
        app.buttons["Customize"].tapWhenSettled()
        app.buttons["settings.row.Health"].tapWhenSettled()
        XCTAssertTrue(app.buttons["health.startSetup"].waitForExistence(timeout: 3))
        capture("health-introduction")
        app.buttons["health.startSetup"].tap()
        capture("health-setup-accounts")
        app.buttons["health.setupContinue"].tap()
        capture("health-setup-conditions")
        app.buttons["Skip for now"].tap()
        app.buttons["Skip for now"].tapWhenSettled()
        app.buttons["Done"].tapWhenSettled()
        XCTAssertTrue(app.buttons["Health menu"].waitForExistence(timeout: 3))
        capture("health-home")
        app.buttons["Records"].tap()
        capture("health-records")
        app.buttons["Chats"].tap()
        capture("health-chats")
        app.buttons["Accounts"].tap()
        capture("health-accounts")
        app.buttons["health.add-account"].tap()
        capture("health-providers")
    }
    @MainActor func testFinanceAccountAndDashboardFlow() {
        let app = XCUIApplication()
        app.launchArguments = ["--ui-test"]
        app.launch()
        app.buttons["sidebarButton"].tap()
        app.buttons["Customize"].tapWhenSettled()
        app.buttons["settings.row.Finances"].tapWhenSettled()
        XCTAssertTrue(app.buttons["Finance menu"].waitForExistence(timeout: 3))
        capture("finance-dashboard")
        app.buttons["Accounts"].tap()
        capture("finance-accounts")
        app.buttons["Add account"].tap()
        capture("finance-add-account")
        app.buttons["Manual accounts"].tap()
        app.buttons["finance.manual.Cash"].tapWhenSettled()
        XCTAssertTrue(app.buttons["Back to finances"].waitForExistence(timeout: 3))
        capture("finance-cash-chat")
        app.buttons["Back to finances"].tap()
        app.buttons["Transactions"].tapWhenSettled()
        app.buttons["Filter transactions"].tapWhenSettled()
        capture("finance-filters")
        app.buttons["finance.filter.dates"].tap()
        app.buttons["finance.filter.date.Last month"].tapWhenSettled()
        app.buttons["Finance menu"].tapWhenSettled()
        app.buttons["Customize dashboard"].tapWhenSettled()
        capture("finance-customize")
        app.buttons["Cancel dashboard customization"].tap()
    }
}
