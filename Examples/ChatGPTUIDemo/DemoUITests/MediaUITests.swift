import XCTest

final class MediaUITests: XCTestCase {
    @MainActor func testMediaPickerComposerContextAndViewer() {
        let app = XCUIApplication()
        app.launchArguments = ["--ui-test"]
        app.launch()
        let id = "10000000-0000-0000-0000-000000000000"
        app.buttons["attachmentMenu"].tap()
        app.buttons["Photos"].tap()
        XCTAssertTrue(app.buttons["photos.item." + id].waitForExistence(timeout: 3))
        capture("photos-recent")
        app.buttons["photos.item." + id].tap()
        capture("photos-selected")
        app.buttons["photos.add"].tap()
        XCTAssertTrue(app.buttons["Remove image Garden notes 1"].waitForExistence(timeout: 3))
        capture("image-composer")
        app.buttons["Remove image Garden notes 1"].tap()
        XCTAssertFalse(app.buttons["Remove image Garden notes 1"].exists)
        app.buttons["attachmentMenu"].tap()
        app.buttons["Photos"].tap()
        app.buttons["photos.item." + id].tap()
        app.buttons["photos.add"].tap()
        app.buttons["composerPrimaryButton"].tap()
        app.buttons["composerPrimaryButton"].tap()
        let media = app.buttons["message.media." + id]
        XCTAssertTrue(media.waitForExistence(timeout: 3))
        XCTAssertFalse(media.label.hasPrefix("Play video"))
        XCTAssertEqual(media.frame.width, 185, accuracy: 1)
        capture("sent-image")
        media.press(forDuration: 0.8)
        XCTAssertTrue(app.buttons["Copy"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.buttons["Edit"].exists)
        capture("sent-image-context")
        app.buttons["Copy"].tap()
        media.tap()
        XCTAssertTrue(app.buttons["media.close"].waitForExistence(timeout: 3))
        capture("sent-image-viewer")
        app.buttons["media.options"].tap()
        capture("sent-image-viewer-menu")
        app.buttons["Add to Favorites"].tap()
        app.buttons["media.image"].firstMatch.tap()
        XCTAssertFalse(app.buttons["media.close"].exists)
        capture("sent-image-viewer-hidden")
        app.buttons["media.image"].firstMatch.tap()
        XCTAssertTrue(app.buttons["media.close"].exists)
        app.buttons["media.close"].tap()
        media.tap()
        app.buttons["media.options"].tap()
        XCTAssertTrue(app.buttons["Remove from Favorites"].waitForExistence(timeout: 3))
    }
    @MainActor func testVideoPickerAndViewer() {
        let app = XCUIApplication()
        app.launchArguments = ["--ui-test"]
        app.launch()
        let id = "20000000-0000-0000-0000-000000000000"
        app.buttons["attachmentMenu"].tap()
        app.buttons["Photos"].tap()
        app.swipeUp()
        let video = app.buttons["photos.item." + id]
        XCTAssertTrue(video.waitForExistence(timeout: 3))
        video.tap()
        XCTAssertEqual(app.buttons["photos.add"].label, "Add 1 video")
        capture("photos-video-selected")
        app.buttons["photos.add"].tap()
        XCTAssertEqual(app.descendants(matching: .any)["composer.media." + id].firstMatch.value as? String, "0:08")
        capture("video-composer")
        app.buttons["composerPrimaryButton"].tap()
        app.buttons["composerPrimaryButton"].tap()
        let sentVideo = app.buttons["message.media." + id]
        XCTAssertEqual(sentVideo.label, "Play video Garden clip")
        XCTAssertEqual(sentVideo.frame.width, 120, accuracy: 1)
        XCTAssertEqual(sentVideo.frame.height, 240, accuracy: 1)
        capture("video-sent")
        sentVideo.tap()
        XCTAssertTrue(app.buttons["media.video.fit"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.buttons["media.options"].exists)
        XCTAssertFalse(app.buttons["media.tool.Edit"].exists)
        capture("video-viewer")
        app.buttons["media.video.fit"].tap()
        app.buttons["media.close"].tap()
        XCTAssertTrue(app.buttons["message.media." + id].waitForExistence(timeout: 3))
        sentVideo.press(forDuration: 0.8)
        XCTAssertTrue(app.buttons["media.video.fit"].waitForExistence(timeout: 3))
        XCTAssertFalse(app.buttons["Copy"].exists)
        capture("video-long-press-viewer")
    }
    @MainActor func testCameraEndpoints() {
        let app = XCUIApplication()
        app.launchArguments = ["--ui-test"]
        app.launch()
        app.buttons["attachmentMenu"].tap()
        app.buttons["Camera"].tap()
        XCTAssertTrue(app.buttons["Camera options"].waitForExistence(timeout: 3))
        capture("camera-compact")
        app.buttons["Camera options"].tap()
        capture("camera-expanded")
        XCTAssertEqual(app.buttons["camera.flash"].label, "Flash off")
        app.buttons["camera.flash"].tap()
        XCTAssertEqual(app.buttons["camera.flash"].label, "Flash auto")
        app.buttons["camera.flash"].tap()
        XCTAssertEqual(app.buttons["camera.flash"].label, "Flash on")
        app.buttons["Scan document"].tap()
        capture("camera-scan")
        XCTAssertTrue(app.buttons["Finish scan"].exists)
        app.buttons["Camera back"].tap()
        XCTAssertTrue(app.buttons["Camera options"].exists)
        app.buttons["Camera back"].tap()
        XCTAssertFalse(app.buttons["Camera options"].exists)
        app.buttons["attachmentMenu"].tap()
        app.buttons["Camera"].tap()
        expectation(for: NSPredicate(format: "hittable == true"), evaluatedWith: app.buttons["Camera options"])
        waitForExpectations(timeout: 3)
        app.buttons["Camera options"].tap()
        app.buttons["Scan document"].tap()
        app.buttons["camera.shutter"].tap()
        app.buttons["Finish scan"].tap()
        XCTAssertTrue(app.staticTexts["Scanned document.pdf"].waitForExistence(timeout: 3))
    }
}
